beatles = ['John Lennon', 'Paul McCartney', 'George Harrison', 'Ringo Starr']

# Using += operator
beatles += ['pratik Giri', 'Aditya Rai']
print(beatles)

# Using append() method
beatles.append('Sajan Giri')
print(beatles)

# Using insert() method
beatles.insert(4, 'Parbhat Bhurtal')
print(beatles)

# Using extend() method
nirvana = ['Kurt Cobain', 'Krist Novoselic', 'Dave Grohl']
beatles.extend(nirvana)
print(beatles)
