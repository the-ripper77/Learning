# Comparison operators return True or False based on the comparison
x = 5
y = 3

# Equal
print(x == y)

# Not equal
print(x != y)

# Greater than
print(x > y)

# Less than
print(x < y)

# Greater than or equal to
print(x >= y)

# Less than or equal to
print(x <= y)

# Chaining Comparison Operators
x = 5
print(1 < x < 10)
print(1 < x and x < 10) #logical operators